import { chromium } from 'playwright-core'
const url = process.env.URL ?? 'http://127.0.0.1:5477/'
const out = process.env.OUT ?? '/tmp/shots'
const browser = await chromium.launch({ executablePath: '/usr/local/bin/google-chrome', args: ['--no-sandbox'] })
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(`pageerror: ${e.message}`))
page.on('console', (m) => { if (m.type() === 'error') errors.push(`console.error: ${m.text().slice(0, 200)}`) })
await page.goto(url, { waitUntil: 'networkidle' })
await page.evaluate(() => localStorage.clear())
await page.reload({ waitUntil: 'networkidle' })
await page.waitForTimeout(1500)
await page.screenshot({ path: `${out}/m-menu.png` })
await page.locator('button', { hasText: 'Game modes inside' }).click()
await page.waitForTimeout(700)
await page.screenshot({ path: `${out}/m-formats.png` })
await page.locator('button', { hasText: 'Pack Rip' }).first().click()
await page.waitForTimeout(900)
await page.screenshot({ path: `${out}/m-setup.png`, fullPage: false })
await page.getByRole('button', { name: /Start draft/i }).click()
await page.waitForTimeout(500)
await page.getByRole('button', { name: /Skip/i }).click()
await page.getByRole('button', { name: /Start the draft/i }).click()
await page.waitForTimeout(500)
await page.getByRole('button', { name: /Quick CPU picks/i }).click()
await page.waitForTimeout(3500)
await page.screenshot({ path: `${out}/m-draft-pack.png` })
const card = page.locator('[role="button"][aria-label*="overall"]').first()
if (await card.count()) await card.click({ force: true })
await page.waitForTimeout(600)
await page.screenshot({ path: `${out}/m-draft-selected.png` })
await page.getByRole('button', { name: /Scout & Roster/i }).click()
await page.waitForTimeout(500)
await page.screenshot({ path: `${out}/m-draft-scout.png` })
console.log('errors:', errors.length ? errors : 'none')
await browser.close()
